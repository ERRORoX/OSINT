"""Developer CLI for OSINT Panel modules.

Usage:
  python backend/module_cli.py list
  python backend/module_cli.py check
  python backend/module_cli.py create my-tool --name "My Tool" --category other
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = BACKEND_DIR.parent
if str(BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(BACKEND_DIR))

from module_registry import discover_modules
from module_runtime import load_integrated_tools

MODULE_ID_RE = re.compile(r"^[a-z0-9][a-z0-9-]{1,62}$")
CATEGORIES = ("domain", "identity", "photo", "network", "education", "utility", "workspace", "other")


def create_module(module_id: str, name: str, category: str) -> Path:
    """Create a safe, disabled module skeleton without overwriting existing files."""
    if not MODULE_ID_RE.fullmatch(module_id):
        raise ValueError("Module id must be 2-63 lowercase letters, digits or hyphens.")
    if category not in CATEGORIES:
        raise ValueError("Unsupported module category.")
    if not name.strip():
        raise ValueError("Module name cannot be empty.")

    tools_root = (PROJECT_ROOT / "tools").resolve()
    target = (tools_root / module_id).resolve()
    if target.parent != tools_root or target.exists():
        raise FileExistsError(f"Module directory already exists or is not a safe child: {target}")

    target.mkdir(parents=True)
    for folder in ("frontend", "backend", "config", "tests"):
        (target / folder).mkdir()

    manifest = {
        "schema_version": 1,
        "id": module_id,
        "name": name.strip(),
        "version": "0.1.0",
        "category": category,
        "description": "",
        "status": "planned",
        "enabled": False,
        "entrypoints": {
            "manifest_readme": f"tools/{module_id}/README.md"
        },
        "dependencies": {"python": [], "system": [], "optional": []},
        "capabilities": [],
        "legacy_paths": [],
        "notes": ["Generated by backend/module_cli.py. Implement and test the module before enabling it."]
    }
    (target / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8"
    )
    readme = (
        f"# {name.strip()}\n\n"
        "## Purpose\nDescribe what this module does and its supported use cases.\n\n"
        "## Structure\n"
        "- frontend/ — module-owned UI\n"
        "- backend/ — module-owned backend implementation\n"
        "- config/ — non-secret defaults and schemas\n"
        "- tests/ — module tests\n"
        "- manifest.json — declarative module metadata\n\n"
        "## Dependencies\nDocument required and optional dependencies in manifest.json. "
        "Never commit API keys or user data.\n"
    )
    (target / "README.md").write_text(readme, encoding="utf-8")
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="OSINT Panel module developer tools")
    parser.add_argument("command", choices=("list", "check", "runtime-check", "create"))
    parser.add_argument("module_id", nargs="?", help="new module id for the create command")
    parser.add_argument("--name", help="display name for a new module")
    parser.add_argument("--category", choices=CATEGORIES, default="other")
    args = parser.parse_args(argv)

    if args.command == "create":
        if not args.module_id or not args.name:
            parser.error("create requires MODULE_ID and --name")
        try:
            path = create_module(args.module_id, args.name, args.category)
        except (ValueError, FileExistsError, OSError) as exc:
            print(f"ERROR: {exc}", file=sys.stderr)
            return 1
        print(f"Created module skeleton: {path.relative_to(PROJECT_ROOT)}")
        print("The module is disabled until its implementation and tests are ready.")
        return 0

    if args.command == "runtime-check":
        loaded, issues = load_integrated_tools(PROJECT_ROOT)
        for tool in loaded:
            print(f"[OK] {tool.tool_id:<22} {tool.name}")
        for item in issues:
            print(f"[ERROR] {item['module_id']}: {item['message']}", file=sys.stderr)
        print(f"\nLoaded: {len(loaded)} | Runtime errors: {len(issues)}")
        return 0 if not issues else 1

    result = discover_modules(PROJECT_ROOT)
    if args.command == "list":
        for module in result["modules"]:
            state = "OK" if module["valid"] else "ERROR"
            enabled = "enabled" if module["enabled"] else "disabled"
            print(f"[{state}] {module['id']:<22} {module['name']} ({module['status']}, {enabled})")
        summary = result["summary"]
        print(
            f"\nDiscovered: {summary['discovered']} | Valid: {summary['valid']} | "
            f"Invalid: {summary['invalid']} | Enabled: {summary['enabled']}"
        )
        return 0 if summary["invalid"] == 0 else 1

    print(json.dumps(result, ensure_ascii=False, indent=2))
    summary = result["summary"]
    return 0 if summary["invalid"] == 0 and not result["issues"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
